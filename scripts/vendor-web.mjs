// Copies the flight search modules into the web source as plain JavaScript, so the browser runs the
// SAME code the server tests run (packages/flights and packages/core), with no second copy to drift.
//
// How: each module is read, its TypeScript types are removed with Node's own stripper (the code uses
// erasable syntax only), and its relative imports are rewritten from .ts to .js. The package folder
// layout is kept, so every relative import still resolves.
//
// Excluded on purpose: supplier adapters (mock and Duffel). The browser must never contain fixture
// fares or a supplier call path. The build check in build-web.mjs also refuses them.
//
// Output: apps/web/src/vendor/ (git-ignored, regenerated on every build and before unit tests).

import { stripTypeScriptTypes } from 'node:module';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const ROOT = join(HERE, '..');
export const VENDOR = join(ROOT, 'apps', 'web', 'src', 'vendor');

// Browser entry points. Everything they import (directly or not) is copied too.
const ENTRIES = [
  'packages/flights/src/search-service.ts',
  'packages/flights/src/airports.ts',
  'packages/flights/src/offer-filters.ts',
  'packages/flights/src/search.ts',
];

const FORBIDDEN_SOURCE = /\/adapters\//;
const IMPORT_TS = /(from\s+|import\s+)['"](\.{1,2}\/[^'"]+?\.ts)['"]/g;

function importsOf(file) {
  const text = readFileSync(file, 'utf8');
  return [...text.matchAll(IMPORT_TS)].map((match) => resolve(dirname(file), match[2]));
}

export function collectModules() {
  const seen = new Set();
  const queue = ENTRIES.map((entry) => join(ROOT, entry));
  while (queue.length > 0) {
    const file = queue.shift();
    if (seen.has(file)) continue;
    if (FORBIDDEN_SOURCE.test(file)) throw new Error(`vendor-web: supplier adapter reached from the browser: ${file}`);
    if (!existsSync(file)) throw new Error(`vendor-web: missing module ${file}`);
    seen.add(file);
    queue.push(...importsOf(file));
  }
  return [...seen].sort();
}

export function vendorModule(file) {
  const rel = relative(ROOT, file).split('\\').join('/');
  const source = readFileSync(file, 'utf8');
  const stripped = stripTypeScriptTypes(source, { mode: 'strip', sourceUrl: file });
  const rewritten = stripped.replace(/(from\s+['"])(\.{1,2}\/[^'"]+?)\.ts(['"])/g, '$1$2.js$3');
  const banner = `// Generated by scripts/vendor-web.mjs from ${rel}. Do not edit: change the TypeScript source.\n`;
  return { outPath: join(VENDOR, rel.replace(/\.ts$/, '.js')), code: banner + rewritten };
}

export function vendor() {
  rmSync(VENDOR, { recursive: true, force: true });
  const files = collectModules();
  for (const file of files) {
    const { outPath, code } = vendorModule(file);
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, code);
  }
  // Design tokens come from the shared UI package, so the web app and any future surface use one source.
  mkdirSync(VENDOR, { recursive: true });
  copyFileSync(join(ROOT, 'packages', 'ui', 'src', 'tokens.css'), join(VENDOR, 'tokens.css'));
  return files.length;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const count = vendor();
    console.log(`vendor-web: ${count} flight modules and tokens copied to ${relative(ROOT, VENDOR)}.`);
    process.exitCode = 0;
  } catch (error) {
    console.error(`vendor-web: ${error.message}`);
    process.exitCode = 1;
  }
}
