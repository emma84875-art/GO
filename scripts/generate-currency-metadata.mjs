// Generates packages/core/src/currency-metadata.ts from the committed SIX ISO 4217 List One XML.
// Run: node scripts/generate-currency-metadata.mjs
// The output is deterministic: the same XML always produces the same file.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const SOURCE_FILE = 'packages/core/data/iso-4217-list-one-2026-09-17.xml';
const OUTPUT = join(root, 'packages/core/src/currency-metadata.ts');
const PUBLISHED = '2026-09-17';
const RETRIEVED = '2026-11-26';
const PROVENANCE = 'six-list-one-2026-09-17';

// Codes that were in the earlier runtime snapshot but are absent from List One. Their historical status and
// minor units are NOT verified against any historical list, so they are kept as legacy, never as current.
const LEGACY = [
  { code: 'ANG', name: 'Netherlands Antillean Guilder', exponent: 2 },
  { code: 'BGN', name: 'Bulgarian Lev', exponent: 2 },
  { code: 'CUC', name: 'Cuban Convertible Peso', exponent: 2 },
  { code: 'HRK', name: 'Croatian Kuna', exponent: 2 },
  { code: 'SLL', name: 'Sierra Leonean Leone (old)', exponent: 0 },
  { code: 'ZWL', name: 'Zimbabwe Dollar', exponent: 2 },
];

const xml = readFileSync(join(root, SOURCE_FILE), 'utf8');
const byCode = new Map();
for (const [, block] of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
  const code = (block.match(/<Ccy>([^<]*)<\/Ccy>/) ?? [])[1];
  if (!code) continue;
  const nameMatch = block.match(/<CcyNm(?: IsFund="(true|false)")?>([^<]*)<\/CcyNm>/);
  const units = (block.match(/<CcyMnrUnts>([^<]*)<\/CcyMnrUnts>/) ?? [])[1];
  const number = (block.match(/<CcyNbr>([^<]*)<\/CcyNbr>/) ?? [])[1];
  const rec = byCode.get(code) ?? { code, name: nameMatch?.[2] ?? '', number, units, fund: false };
  if (nameMatch?.[1] === 'true') rec.fund = true;
  if (!rec.name && nameMatch) rec.name = nameMatch[2];
  if (rec.units === undefined && units !== undefined) rec.units = units;
  byCode.set(code, rec);
}

const entries = [...byCode.values()].map((rec) => {
  let classification = 'currency';
  if (rec.fund) classification = 'fund';
  else if (rec.units === 'N.A.' || rec.units === undefined) classification = 'special';
  // Funds keep their official minor unit (for reference). Special codes have none (N.A.).
  const numeric = rec.units !== undefined && /^\d+$/.test(rec.units) ? Number(rec.units) : null;
  const exponent = numeric;
  if (classification === 'currency' && exponent === null) throw new Error(`bad exponent for ${rec.code}`);
  return { code: rec.code, name: rec.name, number: rec.number, exponent, classification, listStatus: 'current', provenance: PROVENANCE };
});
for (const legacy of LEGACY) {
  if (byCode.has(legacy.code)) throw new Error(`${legacy.code} is in List One; it must not be legacy`);
  entries.push({
    code: legacy.code, name: legacy.name, number: null, exponent: legacy.exponent,
    classification: 'currency', listStatus: 'legacy', provenance: 'legacy-not-in-list-one-unverified',
  });
}
entries.sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0));

const counts = {
  total: entries.length,
  currentCurrency: entries.filter((e) => e.classification === 'currency' && e.listStatus === 'current').length,
  legacyCurrency: entries.filter((e) => e.classification === 'currency' && e.listStatus === 'legacy').length,
  fund: entries.filter((e) => e.classification === 'fund').length,
  special: entries.filter((e) => e.classification === 'special').length,
};

const line = (e) => `  { code: ${JSON.stringify(e.code)}, name: ${JSON.stringify(e.name)}, number: ${JSON.stringify(e.number)}, exponent: ${e.exponent === null ? 'null' : e.exponent}, classification: ${JSON.stringify(e.classification)}, listStatus: ${JSON.stringify(e.listStatus)}, provenance: ${JSON.stringify(e.provenance)} },`;

const out = `// Currency metadata shared by the server and the browser. GENERATED by scripts/generate-currency-metadata.mjs
// from packages/core/data/iso-4217-list-one-2026-09-17.xml. Edit the XML or the script, then regenerate. Do not
// edit this file by hand. A test checks that every official entry here matches the XML.
//
// Source: ISO 4217 List One, SIX Group Maintenance Agency, publication date ${PUBLISHED}.
// Retrieved (supplied by the owner as an upload): ${RETRIEVED}.
// Counts: ${counts.total} entries, ${counts.currentCurrency} current currencies, ${counts.legacyCurrency} legacy currencies,
// ${counts.fund} funds, ${counts.special} special-purpose codes.
//
// classification: 'currency' (an ordinary currency), 'fund' (flagged IsFund="true" in List One), or 'special'
//   (precious metal, unit of account, testing or no-currency code: minor unit N.A. in List One).
// listStatus: 'current' (in List One) or 'legacy' (not in List One; historical status not verified against any
//   historical list, so it is never called withdrawn here).
//
// Rules (see money.ts):
//   new amounts and new supplier offers: classification 'currency' AND listStatus 'current'.
//   stored records: classification 'currency' with any listStatus (legacy codes still display).
//   funds and special codes are never ordinary flight currencies.

export const CURRENCY_METADATA_VERSION = '${PROVENANCE}';
export const CURRENCY_METADATA_SOURCE =
  'ISO 4217 List One, SIX Group Maintenance Agency, publication ${PUBLISHED} (committed as packages/core/data/iso-4217-list-one-2026-09-17.xml).';
export const CURRENCY_METADATA_PUBLISHED = '${PUBLISHED}';
export const CURRENCY_METADATA_RETRIEVED_UTC = '${RETRIEVED}';

export type CurrencyClassification = 'currency' | 'fund' | 'special';
export type ListStatus = 'current' | 'legacy';

export interface CurrencyEntry {
  readonly code: string;
  readonly name: string;
  readonly number: string | null;
  readonly exponent: number | null;
  readonly classification: CurrencyClassification;
  readonly listStatus: ListStatus;
  readonly provenance: string;
}

export const CURRENCY_ENTRIES: readonly CurrencyEntry[] = Object.freeze([
${entries.map(line).join('\n')}
]);
`;
writeFileSync(OUTPUT, out, 'utf8');
console.log(JSON.stringify(counts));
